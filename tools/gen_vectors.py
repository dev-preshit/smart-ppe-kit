#!/usr/bin/env python3
"""SC-03 gen_vectors.py - Appendix A vectors, 136 bit-flip variants, filter-defect set and forged set.

Writes a C++ header consumed by the host tests. Expected values come from this script and the
spec text, NEVER from the code under test (test plan 5.1 rule 3).
Usage: python3 tools/gen_vectors.py [out_header]   (default test/host/gen/vectors.h)
"""
import hashlib, hmac, os, random, sys

TEST_KEY = bytes(range(32))          # protocol spec Appendix A, TEST ONLY
HUB_VEST = 1
# result codes = enum ppe_rx_result_t order in ppe_filter.h
OK, DROP_LEN, DROP_VER, DROP_VEST, DROP_NODE, HMAC_FAIL, DROP_STATE = range(7)

# Spec Appendix A, typed from the document (independent of the computation below).
A1_INPUT = bytes.fromhex("60 01 03 01 5A 02 01 00 00".replace(" ", ""))
A1_TAG = bytes.fromhex("32 22 11 1B D5 0A 5B 34".replace(" ", ""))
A1_FULL = "3222111bd50a5b34d531d0ce9aa7dbd39f985e938c82f9c6f10158d5733ca3c3"
A2_INPUT = bytes.fromhex("40 01 05 00 32 03 01 00 00".replace(" ", ""))
A2_TAG = bytes.fromhex("41 B4 7A 3B 28 82 2B 6A".replace(" ", ""))

def tag(inp, key=TEST_KEY):
    return hmac.new(key, inp, hashlib.sha256).digest()[:8]

def payload(flags, vest, node, state, batt, ctr, key=TEST_KEY):
    inp = bytes([flags, vest, node, state, batt]) + ctr.to_bytes(4, "little")
    return inp + tag(inp, key)

def adv(p):
    return bytes([0x14, 0xFF, 0xFF, 0xFF]) + p

def expected_stage(p, hub_vest=HUB_VEST):
    """Spec section 2 order, written independently of ppe_filter.cpp."""
    if (p[0] >> 6) != 1: return DROP_VER
    if p[1] != hub_vest: return DROP_VEST
    if not 1 <= p[2] <= 5: return DROP_NODE
    if tag(p[:9]) != p[9:17]: return HMAC_FAIL
    if p[3] not in (0, 1): return DROP_STATE
    return OK

def self_check():
    a1 = A1_INPUT + A1_TAG
    assert hmac.new(TEST_KEY, A1_INPUT, hashlib.sha256).hexdigest() == A1_FULL, "A.1 full digest mismatch"
    assert tag(A1_INPUT) == A1_TAG, "A.1 tag mismatch"
    assert tag(A2_INPUT) == A2_TAG, "A.2 tag mismatch"
    assert adv(a1) == bytes.fromhex("14FFFFFF60010301 5A02010000 3222111BD50A5B34".replace(" ", "")), "A.1 adv mismatch"
    return a1, A2_INPUT + A2_TAG

def arr(b):
    return "{" + ",".join("0x%02X" % x for x in b) + "}"

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "test", "host", "gen", "vectors.h")
    a1, a2 = self_check()
    L = ["// GENERATED by tools/gen_vectors.py - do not edit, do not commit.", "#pragma once", "#include <stdint.h>",
         "static const uint8_t V_KEY[32] = %s;" % arr(TEST_KEY),
         "static const uint8_t V_A1_PAYLOAD[17] = %s;" % arr(a1),
         "static const uint8_t V_A1_ADV[21] = %s;" % arr(adv(a1)),
         "static const uint8_t V_A1_FULL_HMAC[32] = %s;" % arr(bytes.fromhex(A1_FULL)),
         "static const uint8_t V_A2_PAYLOAD[17] = %s;" % arr(a2)]
    # 136 single-bit flips of A.1 bytes 0..16
    flips, fexp = [], []
    for byte in range(17):
        for bit in range(8):
            q = bytearray(a1); q[byte] ^= 1 << bit
            flips.append(bytes(q)); fexp.append(expected_stage(bytes(q)))
    assert len(flips) == 136 and all(e != OK for e in fexp)
    L.append("static const uint8_t V_FLIPS[136][17] = {" + ",\n".join(arr(f) for f in flips) + "};")
    L.append("static const uint8_t V_FLIP_EXPECT[136] = {" + ",".join(map(str, fexp)) + "};")
    # defect set: each is a full 21-byte adv (or other length) with the expected counter
    base = lambda **k: payload(k.get("flags", 0x60), k.get("vest", 1), k.get("node", 3), k.get("state", 1), 90, k.get("ctr", 258))
    cases = []   # (name, bytes, nonconn, expect)
    cases.append(("len20", adv(base())[:20], 1, DROP_LEN))
    cases.append(("len22", adv(base()) + b"\x00", 1, DROP_LEN))
    cases.append(("len0", b"", 1, DROP_LEN))
    for i, nm in enumerate(["adlen", "adtype", "cid_lo", "cid_hi"]):
        d = bytearray(adv(base())); d[i] ^= 0x01
        cases.append(("hdr_" + nm, bytes(d), 1, DROP_LEN))
    cases.append(("not_nonconn_pdu", adv(base()), 0, DROP_LEN))
    for v in (0, 2, 3):
        cases.append(("ver%d" % v, adv(payload((v << 6) | 0x20, 1, 3, 1, 90, 258)), 1, DROP_VER))
    cases.append(("wrong_vest", adv(payload(0x60, 2, 3, 1, 90, 258)), 1, DROP_VEST))
    for n in (0, 6, 0xFF):
        cases.append(("node%d" % n, adv(payload(0x60, 1, n, 1, 90, 258)), 1, DROP_NODE))
    cases.append(("state02_valid_hmac", adv(payload(0x60, 1, 3, 2, 90, 258)), 1, DROP_STATE))
    cases.append(("state_ff_valid_hmac", adv(payload(0x60, 1, 3, 0xFF, 90, 258)), 1, DROP_STATE))
    # two defects: wrong vest AND bad version -> version wins; unknown node AND bad HMAC -> drop_node wins
    cases.append(("two_ver_vest", adv(payload(0x20, 2, 3, 1, 90, 258)), 1, DROP_VER))
    bad = bytearray(adv(base(node=6))); bad[-1] ^= 1
    cases.append(("two_node_hmac", bytes(bad), 1, DROP_NODE))
    bad = bytearray(adv(base(state=2))); bad[-1] ^= 1
    cases.append(("two_state_hmac", bytes(bad), 1, HMAC_FAIL))   # HMAC is checked before state
    cases.append(("valid_a1", adv(a1), 1, OK))
    cases.append(("valid_reserved_bits_set", adv(payload(0x63, 1, 3, 1, 90, 258)), 1, OK))
    L.append("struct VCase { const char* name; uint8_t nonconn; uint8_t len; uint8_t data[24]; uint8_t expect; };")
    L.append("static const VCase V_CASES[] = {")
    for nm, d, nc, ex in cases:
        pad = d + b"\x00" * (24 - len(d))
        L.append('  {"%s",%d,%d,%s,%d},' % (nm, nc, len(d), arr(pad), ex))
    L.append("};")
    L.append("static const unsigned V_CASES_N = %d;" % len(cases))
    # 1000 random forged packets: valid format, vest, node; random tag (seeded)
    rnd = random.Random(0x5EED1)
    forged = []
    for _ in range(1000):
        p = bytes([0x60 | rnd.choice([0, 0x10, 0x08, 0x04]), 1, rnd.randint(1, 5), rnd.randint(0, 1), rnd.randint(0, 100)]) \
            + rnd.getrandbits(32).to_bytes(4, "little") + rnd.randbytes(8)
        if tag(p[:9]) == p[9:]: continue
        forged.append(p)
    L.append("static const uint8_t V_FORGED[%d][17] = {" % len(forged) + ",\n".join(arr(f) for f in forged) + "};")
    L.append("static const unsigned V_FORGED_N = %d;" % len(forged))
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as f: f.write("\n".join(L) + "\n")
    print("gen_vectors: wrote %s (136 flips, %d defect cases, %d forged)" % (out, len(cases), len(forged)))

if __name__ == "__main__":
    main()
